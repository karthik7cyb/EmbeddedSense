
from langchain.agents import create_agent
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_groq import ChatGroq

from app.ai.tools.currency import convert_currency
from app.core.config import settings
from app.ai.prompts.gemini_prompt import SYSTEM_PROMPT


# ---------------------------------------------------------
# SHARED LLM TOOLS
# ---------------------------------------------------------

LLM_tools = [
    convert_currency,
]


# ---------------------------------------------------------
# MODELS
# ---------------------------------------------------------

class Models:

    def __init__(self):

        # PRIMARY MODEL: GEMINI
        primary_model = ChatGoogleGenerativeAI(
            model="gemini-3.5-flash-lite",
            google_api_key=settings.GEMINI_API_KEY,
            temperature=0.2,
        )

        # FALLBACK MODEL: GROQ
        fallback_model = ChatGroq(
            model="openai/gpt-oss-20b",
            api_key=settings.GROQ_API_KEY,
            temperature=0.2,
        )

        # TEMPORARILY USE GEMINI DIRECTLY
        self.llm = primary_model

        # CREATE LANGCHAIN AGENT
        self.agent = create_agent(
            model=self.llm,
            tools=LLM_tools,
            system_prompt=SYSTEM_PROMPT,
        )

    # -----------------------------------------------------
    # SYNCHRONOUS INVOCATION
    # -----------------------------------------------------

    def gemini_llm(self, prompt: str):

        response = self.agent.invoke(
            {
                "messages": [
                    {"role": "user", "content": prompt}
                ]
            }
        )

        return response["messages"][-1].content

    # -----------------------------------------------------
    # ASYNCHRONOUS STREAMING
    # -----------------------------------------------------

    async def stream_llm(self, prompt: str):

        async for message, metadata in self.agent.astream(
            {
                "messages": [
                    {"role": "user", "content": prompt}
                ]
            },
            stream_mode="messages",
        ):

            # Only process messages generated by the model node
            if metadata.get("langgraph_node") != "model":
                continue

            # Extract text blocks
            for block in message.content_blocks:

                if block.get("type") == "text":

                    text = block.get("text")

                    if text:
                        yield text


# ---------------------------------------------------------
# GLOBAL MODEL INSTANCE
# ---------------------------------------------------------

models = Models()
